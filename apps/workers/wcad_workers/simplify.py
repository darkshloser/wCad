from __future__ import annotations

import math
from typing import Final, Sequence

Coord2 = tuple[float, float]

# Matches LOD_TOLERANCES in douglasPeucker.ts and the geom_lod1..3 columns, in CRS units.
LOD_TOLERANCES: Final[tuple[float, float, float]] = (1.0, 10.0, 100.0)


def perpendicular_distance(p: Coord2, a: Coord2, b: Coord2) -> float:
    """Distance from p to the infinite line through a and b, which is how DP is defined."""
    dx = b[0] - a[0]
    dy = b[1] - a[1]
    len2 = dx * dx + dy * dy
    if len2 == 0:
        return math.hypot(p[0] - a[0], p[1] - a[1])
    return abs(dy * p[0] - dx * p[1] + b[0] * a[1] - b[1] * a[0]) / math.sqrt(len2)


def simplify(points: Sequence[Coord2], tolerance: float) -> list[Coord2]:
    if not (tolerance > 0):
        return [(p[0], p[1]) for p in points]
    if len(points) <= 2:
        return [(p[0], p[1]) for p in points]

    keep = bytearray(len(points))
    keep[0] = 1
    keep[len(points) - 1] = 1

    stack: list[tuple[int, int]] = [(0, len(points) - 1)]
    while stack:
        first, last = stack.pop()
        if last <= first + 1:
            continue
        max_dist = -1.0
        index = -1
        a = points[first]
        b = points[last]
        for i in range(first + 1, last):
            d = perpendicular_distance(points[i], a, b)
            if d > max_dist:
                max_dist = d
                index = i
        if max_dist > tolerance and index > first:
            keep[index] = 1
            # Push order mirrors the TypeScript, so both sides visit segments in the same order.
            stack.append((first, index))
            stack.append((index, last))

    return [(points[i][0], points[i][1]) for i in range(len(points)) if keep[i] == 1]


def build_lod_pyramid(points: Sequence[Coord2]) -> list[list[Coord2]]:
    """Builds the full LOD ladder for one geometry, matching buildLodPyramid on the TS side."""
    return [simplify(points, t) for t in LOD_TOLERANCES]
