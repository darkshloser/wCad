"""
Douglas-Peucker generalization — the Python half of a shared definition.

packages/geo-core/src/simplify/douglasPeucker.ts is the reference implementation. This must
produce identical output for the same input and tolerance, because the client generalizes the
working set with the TypeScript version while the importer writes the LOD columns with this one.
If they disagree, the backdrop and the working set draw the same geometry differently and the
drawing appears to change as elements are selected.

Identical means identical, not close: the arithmetic below mirrors the TypeScript expression by
expression, including operation order, because IEEE-754 addition is not associative and a
rearranged formula produces different last bits. test_simplify_parity.py checks this against
cases generated by the TypeScript side.

Iterative rather than recursive, so a multi-million-vertex polyline cannot exhaust the stack.
"""

